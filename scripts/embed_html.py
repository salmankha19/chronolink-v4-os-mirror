#!/usr/bin/env python3
"""
embed_html.py

Convert an HTML file into a C source file with a raw byte array,
so it can be compiled into the firmware without relying on
ESP-IDF EMBED_FILES or PlatformIO embed_txtfiles.

Usage:
    python scripts/embed_html.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
HTML_IN = ROOT / "components" / "svc_http" / "www" / "index.html"
C_OUT   = ROOT / "components" / "svc_http" / "src" / "index_html.c"

def main():
    if not HTML_IN.exists():
        print(f"ERROR: {HTML_IN} not found", file=sys.stderr)
        sys.exit(1)

    data = HTML_IN.read_bytes()

    with C_OUT.open("w", newline="\n") as f:
        f.write("/*\n")
        f.write(" * index_html.c\n")
        f.write(" *\n")
        f.write(" * Auto-generated by scripts/embed_html.py — do not edit.\n")
        f.write(f" * Source: components/svc_http/www/index.html ({len(data)} bytes)\n")
        f.write(" */\n\n")
        f.write("#include <stddef.h>\n\n")
        f.write("const unsigned char index_html[] = {\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i+16]
            line = ", ".join(f"0x{b:02x}" for b in chunk)
            f.write(f"    {line},\n")
        f.write("};\n\n")
        f.write(f"const size_t index_html_len = {len(data)};\n")

    print(f"Generated {C_OUT} ({len(data)} bytes)")

if __name__ == "__main__":
    main()
