#!/usr/bin/env python3
"""
generate_font_ui_sans.py

Generate components/font/src/font_ui_sans.c for ChronoLink V4 OS.

Modes:
  --builtin       Generate placeholder from built-in 8x8 mono font.
  --ttf <path>    Generate from a TrueType font using Pillow.

The output defines FONT_UI_SANS (id=1, FONT_FORMAT_RGB565, FONT_SCRIPT_LATIN).
"""

import argparse
import re
import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    Image = None
    ImageDraw = None
    ImageFont = None

DEFAULT_FIRST_CHAR = 0x20
DEFAULT_LAST_CHAR = 0x7E


def parse_builtin_font(path):
    """Parse font_builtin_8x8.c and return a dict {char_code: [8 bytes]}."""
    text = path.read_text()
    m = re.search(r'static const uint8_t font_builtin_8x8_data\[\] = \{(.*?)\};', text, re.DOTALL)
    if not m:
        raise ValueError("Could not find font_builtin_8x8_data array in " + str(path))
    array_text = m.group(1)
    array_text = re.sub(r'/\*.*?\*/', '', array_text, flags=re.DOTALL)
    hex_bytes = re.findall(r'0x[0-9A-Fa-f]{2}', array_text)
    data = [int(b, 16) for b in hex_bytes]
    glyphs = {}
    for i in range(0, len(data), 8):
        char_code = 0x20 + (i // 8)
        if char_code > 0x7E:
            break
        glyphs[char_code] = data[i:i+8]
    return glyphs


def builtin_to_rgb565(glyph_bytes):
    """Convert an 8x8 mono bitmap (list of 8 bytes) to a list of 64 RGB565 pixels."""
    pixels = []
    for row in glyph_bytes:
        for bit in range(8):
            if row & (0x80 >> bit):
                pixels.append(0xFFFF)
            else:
                pixels.append(0x0000)
    return pixels


def generate_from_builtin(out_path, first_char, last_char):
    builtin_path = Path(__file__).parent.parent / "components" / "font" / "src" / "font_builtin_8x8.c"
    if not builtin_path.exists():
        print(f"Error: {builtin_path} not found", file=sys.stderr)
        sys.exit(1)
    glyphs = parse_builtin_font(builtin_path)

    glyph_entries = []
    all_pixels = []
    for ch in range(first_char, last_char + 1):
        if ch in glyphs:
            pixels = builtin_to_rgb565(glyphs[ch])
            offset = len(all_pixels)
            all_pixels.extend(pixels)
            glyph_entries.append((ch, 8, offset))
        else:
            glyph_entries.append((ch, 0, 0))

    write_c_file(out_path, first_char, last_char, glyph_entries, all_pixels, native_h=8)


def generate_from_ttf(out_path, ttf_path, first_char, last_char, native_h=64):
    if Image is None:
        print("Error: Pillow (PIL) is required for TTF mode. Install with 'pip install Pillow'", file=sys.stderr)
        sys.exit(1)

    font = ImageFont.truetype(str(ttf_path), native_h)
    ascent, descent = font.getmetrics()
    glyph_entries = []
    all_pixels = []

    for ch in range(first_char, last_char + 1):
        char = chr(ch)
        img = Image.new('L', (native_h * 2, native_h), 0)
        draw = ImageDraw.Draw(img)
        draw.text((0, ascent), char, font=font, fill=255)
        bbox = img.getbbox()
        if bbox is None:
            glyph_entries.append((ch, 0, 0))
            continue
        left, top, right, bottom = bbox
        w = right - left
        glyph_img = img.crop((left, 0, right, native_h))
        pixels = []
        for y in range(native_h):
            for x in range(w):
                pixel = glyph_img.getpixel((x, y))
                pixels.append(0xFFFF if pixel > 128 else 0x0000)
        offset = len(all_pixels)
        all_pixels.extend(pixels)
        glyph_entries.append((ch, w, offset))

    write_c_file(out_path, first_char, last_char, glyph_entries, all_pixels, native_h=native_h)


def write_c_file(out_path, first_char, last_char, glyph_entries, all_pixels, native_h):
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, 'w', newline='\n') as f:
        f.write('#include "font_ui_sans.h"\n\n')
        f.write('/*\n')
        f.write(' * font_ui_sans.c\n')
        f.write(' *\n')
        f.write(' * ChronoLink V4 OS - UI sans-serif font (RGB565)\n')
        f.write(' *\n')
        f.write(' * Auto-generated by scripts/generate_font_ui_sans.py\n')
        f.write(' * Do not edit manually.\n')
        f.write(' */\n\n')
        f.write('static const uint16_t ui_sans_pixels[] = {\n')
        for i in range(0, len(all_pixels), 8):
            chunk = all_pixels[i:i+8]
            f.write('    ' + ', '.join(f'0x{p:04X}' for p in chunk) + ',\n')
        f.write('};\n\n')
        f.write('static const font_glyph_t ui_sans_glyphs[] = {\n')
        for ch, w, offset in glyph_entries:
            char_repr = chr(ch) if 32 <= ch < 127 else '?'
            f.write(f'    /* 0x{ch:02X} \'{char_repr}\' */ {{ {w}, {offset} }},\n')
        f.write('};\n\n')
        f.write('const font_desc_t FONT_UI_SANS = {\n')
        f.write('    .id         = 1,\n')
        f.write(f'    .first_char = 0x{first_char:02X},\n')
        f.write(f'    .last_char  = 0x{last_char:02X},\n')
        f.write('    .format     = FONT_FORMAT_RGB565,\n')
        f.write('    .script     = FONT_SCRIPT_LATIN,\n')
        f.write(f'    .native_h   = {native_h},\n')
        f.write('    .glyphs     = ui_sans_glyphs,\n')
        f.write('    .pixels     = ui_sans_pixels,\n')
        f.write('};\n')
    print(f'Generated {out_path}')


def main():
    parser = argparse.ArgumentParser(description='Generate font_ui_sans.c')
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--builtin', action='store_true', help='Generate from built-in 8x8 mono font')
    group.add_argument('--ttf', type=Path, help='Path to TrueType font file')
    parser.add_argument('--out', type=Path, default=Path('components/font/src/font_ui_sans.c'), help='Output C file')
    parser.add_argument('--first-char', type=lambda x: int(x, 0), default=DEFAULT_FIRST_CHAR, help='First ASCII character (default: 0x20)')
    parser.add_argument('--last-char', type=lambda x: int(x, 0), default=DEFAULT_LAST_CHAR, help='Last ASCII character (default: 0x7E)')
    parser.add_argument('--native-h', type=int, default=64, help='Native height for TTF (default: 64)')
    args = parser.parse_args()

    if args.builtin:
        generate_from_builtin(args.out, args.first_char, args.last_char)
    else:
        generate_from_ttf(args.out, args.ttf, args.first_char, args.last_char, args.native_h)


if __name__ == '__main__':
    main()
